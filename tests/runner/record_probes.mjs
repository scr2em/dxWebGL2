// Records the probe pixels of the runtime test in every mode and writes tests/runtime/expected_probes.inc.
// Run it when a change to the rendering is intended:
//
//   node tests/runner/record_probes.mjs <build-dir>
//
// The values are taken from whatever GL implementation the browser uses; commit the result only when it was
// recorded with the software rasterizer (SwiftShader) so that runs are comparable. They are recorded on the WebGL2
// backend (the WebGPU backend is compared with the same values).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { runTest } from './run_test.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const buildDir = process.argv[2];
if (!buildDir) { console.error('usage: node record_probes.mjs <build-dir>'); process.exit(2); }

const modes = [['default', []], ['shaders', ['--shaders']], ['scene2', ['--scene2']], ['scene3', ['--scene3']]];
const out = ['// SPDX-License-Identifier: GPL-3.0-or-later',
             '// Copyright (C) 2026 dxWebGL2 contributors',
             '// Generated by tests/runner/record_probes.mjs: {mode, probe name, x, y, 0xRRGGBB}.'];
for (const [mode, args] of modes) {
  const r = await runTest(buildDir, null, [...args, '--backend=webgl2']);
  if (!r.done) { console.error(mode + ': timed out'); process.exit(2); }
  for (const l of r.lines) {
    const m = /^PROBE (\S+) \((\d+),(\d+)\) = ([0-9a-f]{6})$/.exec(l);
    if (m) out.push(`{"${mode}", "${m[1]}", ${m[2]}, ${m[3]}, 0x${m[4]}},`);
  }
}
const file = path.join(here, '..', 'runtime', 'expected_probes.inc');
fs.writeFileSync(file, out.join('\n') + '\n');
console.log('wrote ' + file + ' (' + (out.length - 3) + ' probes)');
