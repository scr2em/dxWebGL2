"""Generates the compatibility layer for code written against the original "WebD3D8" library of the game port, from
the public header include/dxwebgl2/dxwebgl2.h:

  include/WebD3D8/WebD3D8.h         forwards to <dxwebgl2/dxwebgl2.h> and maps WebD3D8_* / WEBD3D8_* names to the new ones
                                    with macros (source compatibility)
  src/compat/webd3d8_symbols.cpp    real WebD3D8_* functions that call the dxwebgl2_* ones (link compatibility: for
                                    example a weak `extern "C" WebD3D8_LookupProc` reference in code that never includes
                                    the header)

Usage: tools/gen_webd3d8_compat.py [--check]   (--check only verifies that the files are up to date)
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PUBLIC = os.path.join(ROOT, "include", "dxwebgl2", "dxwebgl2.h")
OUT_HEADER = os.path.join(ROOT, "include", "WebD3D8", "WebD3D8.h")
OUT_SOURCE = os.path.join(ROOT, "src", "compat", "webd3d8_symbols.cpp")

LICENSE = """/* SPDX-License-Identifier: GPL-3.0-or-later
 *
 * Copyright (C) 2026 dxWebGL2 contributors
 *
 * This file is part of dxWebGL2, a Direct3D on WebGL2 translation layer.
 * See the LICENSE file or <https://www.gnu.org/licenses/> for the license terms.
 */
"""


def parse(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\n]*", " ", text)
    enums, structs, funcs = [], [], []
    for m in re.finditer(r"enum\s+(dxwebgl2_\w+)\s*\{([^}]*)\}\s*;", text):
        names = [e.split("=")[0].strip() for e in m.group(2).split(",") if e.strip()]
        enums.append((m.group(1), names))
    text = re.sub(r"enum\s+dxwebgl2_\w+\s*\{[^}]*\}\s*;", " ", text)
    for m in re.finditer(r"typedef\s+struct\s+\w+\s*\{.*?\}\s*(dxwebgl2_\w+)\s*;", text, flags=re.S):
        structs.append(m.group(1))
    text = re.sub(r"typedef\s+struct\s+\w+\s*\{.*?\}\s*dxwebgl2_\w+\s*;", " ", text, flags=re.S)
    for m in re.finditer(r"([A-Za-z_][\w \*]*?)\b(dxwebgl2_\w+)\s*\(([^()]*)\)\s*;", text):
        ret = " ".join(m.group(1).split())
        params = [" ".join(p.split()) for p in m.group(3).split(",")] if m.group(3).strip() not in ("", "void") else []
        funcs.append((ret, m.group(2), params))
    return enums, structs, funcs


# Functions and enumerations that did not exist in the original library.
NEW_ONLY = {"dxwebgl2_GetVersionString", "dxwebgl2_SetBackend", "dxwebgl2_GetBackend"}
NEW_ONLY_ENUMS = {"dxwebgl2_Backend"}


def param_name(p):
    m = re.search(r"(\w+)\s*$", p)
    return m.group(1)


def generate():
    enums, structs, funcs = parse(open(PUBLIC).read())
    funcs = [f for f in funcs if f[1] not in NEW_ONLY]
    enums = [e for e in enums if e[0] not in NEW_ONLY_ENUMS]
    h = [LICENSE, """/*
 * WebD3D8/WebD3D8.h - compatibility header (generated by tools/gen_webd3d8_compat.py, do not edit).
 *
 * dxWebGL2 was extracted from the "WebD3D8" library of the Command & Conquer Generals Zero Hour web port. This header
 * lets code written against that library keep compiling unchanged: it forwards to <dxwebgl2/dxwebgl2.h> and maps the
 * old WebD3D8_* names to the dxwebgl2_* ones. The library also exports the old names as functions, for code that
 * declares them itself.
 *
 * New code should include <dxwebgl2/dxwebgl2.h> and use the dxwebgl2_* names.
 */
#ifndef WEBD3D8_WEBD3D8_H
#define WEBD3D8_WEBD3D8_H

#include <dxwebgl2/dxwebgl2.h>

"""]
    for ret, name, params in funcs:
        h.append("#define WebD3D8_%s %s\n" % (name[len("dxwebgl2_"):], name))
    h.append("\n")
    for name, members in enums:
        h.append("#define WebD3D8_%s %s\n" % (name[len("dxwebgl2_"):], name))
        for e in members:
            h.append("#define WEBD3D8_%s %s\n" % (e[len("DXWEBGL2_"):], e))
    for name in structs:
        h.append("#define WebD3D8_%s %s\n" % (name[len("dxwebgl2_"):], name))
    h.append("\n#endif /* WEBD3D8_WEBD3D8_H */\n")

    c = [LICENSE, """/*
 * The WebD3D8_* entry points of the original library as real functions (generated by tools/gen_webd3d8_compat.py, do
 * not edit): link compatibility for code that declares them itself instead of including <WebD3D8/WebD3D8.h>, for example
 *
 *     extern "C" void *WebD3D8_LookupProc(const char *name) __attribute__((weak));
 *
 * in a Win32 compatibility layer. The object is always linked together with the library (see CMakeLists.txt) so that such
 * weak references resolve.
 */
#include <dxwebgl2/dxwebgl2.h>

extern "C" {

"""]
    for ret, name, params in funcs:
        old = "WebD3D8_" + name[len("dxwebgl2_"):]
        sig = ", ".join(params) if params else "void"
        args = ", ".join(param_name(p) for p in params)
        c.append("%s%s%s(%s)\n{\n    %s%s(%s);\n}\n\n" % (ret, "" if ret.endswith("*") else " ", old, sig, "" if ret == "void" else "return ", name, args))
    c.append("} // extern \"C\"\n")
    return "".join(h), "".join(c)


def main():
    header, source = generate()
    if "--check" in sys.argv:
        ok = True
        for path, text in ((OUT_HEADER, header), (OUT_SOURCE, source)):
            if not os.path.exists(path) or open(path).read() != text:
                print("%s is out of date: run tools/gen_webd3d8_compat.py" % os.path.relpath(path, ROOT))
                ok = False
        if ok:
            print("WebD3D8 compatibility files are up to date")
        return 0 if ok else 1
    for path, text in ((OUT_HEADER, header), (OUT_SOURCE, source)):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(text)
        print("wrote " + os.path.relpath(path, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
